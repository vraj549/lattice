def write_random(setup: dict, meta: dict, mesh_stats: dict, cfg: dict,
                 analysis: dict = None, ai: int = 1) -> CommBuild:
    """Random vibration = a unit-g base sweep spanning the input spectrum.

    Driving with exactly 1 g makes the exported FRF read directly as
    transmissibility, and the response PSD is then |T|^2 * PSD_in, integrated
    in random_vib.py. That keeps the solver side identical to the harmonic
    case which is already proven, instead of relying on a separate random
    operator chain.
    """
    spec = cfg.get("spec") or []
    pts = sorted((float(a), float(b)) for a, b in spec if float(a) > 0)
    if len(pts) < 2:
        raise ValueError("Random vibration needs at least two PSD breakpoints.")
    f0, f1 = pts[0][0], pts[-1][0]
    hcfg = {
        **cfg,
        "excitation": "base",
        "base_g": 1.0,                      # unit input => transmissibility
        "f_min": f0, "f_max": f1,
        "spacing": "log",
        "n_steps": int(cfg.get("n_steps", 600)),
        "field_freqs": cfg.get("field_freqs") or [],
    }
    return write_harmonic(setup, meta, mesh_stats, hcfg, analysis, ai)


WRITERS = {"static": write_static, "modal": write_modal,
           "harmonic": write_harmonic, "random": write_random}


def build_run(analysis: dict, setup: dict, meta: dict, mesh_stats: dict,
              solver_cfg) -> "tuple[str, str]":
    """Returns (comm_text, export_text)."""
    atype = analysis.get("type")
    if atype not in WRITERS:
        raise ValueError(f"Unknown analysis type: {atype}")
    if len(mesh_stats.get("probes", [])) > 6:
        raise ValueError("At most 6 probes are supported (logical unit budget).")
    ai = 1 + next((i for i, a in enumerate(setup.get("analyses", []))
                   if a.get("id") == analysis.get("id")), 0)
    b = WRITERS[atype](setup, meta, mesh_stats, analysis.get("config", {}), analysis, ai)

    exp = [
        "P actions make_etude",
        f"P memory_limit {int(solver_cfg.memory_mb)}",
        f"P time_limit {int(solver_cfg.time_limit_s)}",
        f"P ncpus {int(solver_cfg.ncpus)}",
        "P mpi_nbcpu 1",
        "F comm run.comm D 1",
        "F libr mesh.unv D 19",
    ]
    seen = set()
    for unit, fname in b.result_files:
        if unit in seen:
            continue
        seen.add(unit)
        exp.append(f"F libr {fname} R {unit}")
    exp.append("F mess run.mess R 6")
    return b.text(), "\n".join(exp) + "\n"
