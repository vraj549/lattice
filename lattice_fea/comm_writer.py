def write_static(setup: dict, meta: dict, mesh_stats: dict, cfg: dict,
                 analysis: dict = None, ai: int = 1) -> CommBuild:
    b = CommBuild()
    _prelude(b, setup, meta, mesh_stats, need_probes=False, analysis=analysis, ai=ai)
    fix = _supports(b, analysis, ai)
    load = _loads(b, analysis, ai, meta)
    preload = _preload_charge(b)
    if load is None and preload is None:
        raise ValueError("Static analysis needs at least one load (force, pressure, gravity, or bolt preload).")

    charges = [fix] + b.constraint_charges + ([load] if load else []) + ([preload] if preload else [])
    excit = ", ".join(f"_F(CHARGE={c})" for c in charges)
    b.w("res = MECA_STATIQUE(MODELE=model, CHAM_MATER=chmat,")
    b.w(f"                    EXCIT=({excit},),{_cara_arg(b)}")
    b.w("                    SOLVEUR=_F(METHODE='MUMPS'))")
    b.w()
    vol_restrict = ""
    if getattr(b, "has_beams", False):
        # stress recovery is a solid-element concept; beams get EFGE below
        vol_restrict = "                 GROUP_MA=%s,\n" % _group_tuple(
            ["V%d" % s["tag"] for s in meta.get("solids", [])])
    b.w(f"res = CALC_CHAMP(reuse=res, RESULTAT=res,{_cara_arg(b)}")
    if vol_restrict:
        b.w(vol_restrict.rstrip("\n"))
    b.w("                 CONTRAINTE=('SIGM_NOEU',),")
    b.w("                 CRITERES=('SIEQ_NOEU',),")
    b.w("                 FORCE=('REAC_NODA',))")
    b.w()
    vol_groups = _group_tuple(["V%d" % s["tag"] for s in meta.get("solids", [])])
    b.w("IMPR_RESU(FORMAT='MED', UNITE=80, RESU=_F(")
    b.w("    RESULTAT=res, NOM_CHAM=('DEPL', 'SIEQ_NOEU', 'SIGM_NOEU'),")
    b.w(f"    GROUP_MA={vol_groups}))")
    b.result_files.append((80, "result.med"))
    b.w()
    _bolt_forces_out(b, "res")
    groups = _support_groups(analysis, ai)

    def reactions(x):
        x.w("rtab = POST_RELEVE_T(ACTION=_F(INTITULE='REACTIONS', OPERATION='EXTRACTION',")
        x.w("                               RESULTANTE=('DX', 'DY', 'DZ'),")
        x.w("                               RESULTAT=res, NOM_CHAM='REAC_NODA',")
        x.w(f"                               GROUP_NO={_group_tuple(groups)}))")
        x.w("IMPR_TABLE(TABLE=rtab, UNITE=37, FORMAT='TABLEAU', SEPARATEUR=',')")
        x.result_files.append((37, "tables.txt"))
    _optional(b, "reaction forces", reactions)

    b.w("FIN()")
    return b


def _modal_core(b: CommBuild, setup: dict, cfg: dict, fix: str) -> None:
    """ASSEMBLAGE + CALC_MODES; leaves `modes`, `MK`, `MM`, `nddl` defined.
    Bolt spiders and ties are constraint charges: they belong in the
    assembled operators so beams and glued interfaces carry stiffness in
    modal/harmonic too. Preload does not enter (linear, no stress stiffening)."""
    charges = ", ".join([fix] + b.constraint_charges)
    b.w(f"ASSEMBLAGE(MODELE=model, CHAM_MATER=chmat, CHARGE=({charges},),")
    if getattr(b, "has_beams", False):
        b.w("           CARA_ELEM=cara,")
    b.w("           NUME_DDL=CO('nddl'),")
    b.w("           MATR_ASSE=(_F(MATRICE=CO('MK'), OPTION='RIGI_MECA'),")
    b.w("                      _F(MATRICE=CO('MM'), OPTION='MASS_MECA')))")
    b.w()
    band = cfg.get("band")
    if band:
        b.w("modes = CALC_MODES(MATR_RIGI=MK, MATR_MASS=MM, OPTION='BANDE',")
        b.w(f"                   CALC_FREQ=_F(FREQ=({_fmt(band[0])}, {_fmt(band[1])})),")
    else:
        n = int(cfg.get("n_modes", 10))
        b.w("modes = CALC_MODES(MATR_RIGI=MK, MATR_MASS=MM, OPTION='PLUS_PETITE',")
        b.w(f"                   CALC_FREQ=_F(NMAX_FREQ={n}),")
    b.w("                   SOLVEUR_MODAL=_F(METHODE='SORENSEN'),")
    b.w("                   SOLVEUR=_F(METHODE='MUMPS'),")
    b.w("                   VERI_MODE=_F(STOP_ERREUR='NON'))")
    b.w()


def _optional(b: CommBuild, comment: str, body) -> None:
    """Emit a block that must never abort the run.

    A .comm is executed as Python, so a catchable code_aster <EXCEPTION>
    (a wrong NOM_PARA, a parameter a given version doesn't publish) can be
    contained. Without this, one unavailable table throws away results that
    were already computed — which is exactly what happened to the first real
    modal run.
    """
    b.w(f"# optional: {comment}")
    b.w("try:")
    inner = CommBuild()
    body(inner)
    for line in inner.lines:
        b.w(f"    {line}" if line else "")
    b.result_files.extend(inner.result_files)
    b.w("except Exception as _e:")
    b.w(f"    print('Lattice: skipped {comment} —', _e)")
    b.w()


def write_modal(setup: dict, meta: dict, mesh_stats: dict, cfg: dict,
                analysis: dict = None, ai: int = 1) -> CommBuild:
    b = CommBuild()
    _prelude(b, setup, meta, mesh_stats, need_probes=False, analysis=analysis, ai=ai)
    fix = _supports(b, analysis, ai)
    _modal_core(b, setup, cfg, fix)

    # Mode shapes FIRST: IMPR_RESU is the most stable command here and the
    # result is the expensive one. Tables come after, each individually
    # non-fatal, so a version quirk in a table can't discard the modes.
    b.w("IMPR_RESU(FORMAT='MED', UNITE=80, RESU=_F(RESULTAT=modes, NOM_CHAM='DEPL'))")
    b.result_files.append((80, "result.med"))
    b.w()

    # MODE_MECA numbers modes with NUME_MODE (NUME_ORDRE does not exist on it)
    def freqs(x):
        x.w("ftab = RECU_TABLE(CO=modes, NOM_PARA=('NUME_MODE', 'FREQ'))")
        x.w("IMPR_TABLE(TABLE=ftab, UNITE=38, FORMAT='TABLEAU', SEPARATEUR=',')")
        x.result_files.append((38, "modes.csv"))
    _optional(b, "frequency table", freqs)

    def mass(x):
        x.w("mtab = POST_ELEM(MODELE=model, CHAM_MATER=chmat, MASS_INER=_F(TOUT='OUI'))")
        x.w("IMPR_TABLE(TABLE=mtab, UNITE=37, FORMAT='TABLEAU', SEPARATEUR=',')")
        x.result_files.append((37, "tables.txt"))
    _optional(b, "model mass", mass)

    def part(x):
        x.w("ptab = RECU_TABLE(CO=modes, NOM_PARA=('NUME_MODE', 'FREQ', 'MASS_GENE',")
        x.w("                  'MASS_EFFE_UN_DX', 'MASS_EFFE_UN_DY', 'MASS_EFFE_UN_DZ'))")
        x.w("IMPR_TABLE(TABLE=ptab, UNITE=39, FORMAT='TABLEAU', SEPARATEUR=',')")
        x.result_files.append((39, "participation.csv"))
    _optional(b, "effective mass table", part)

    b.w("FIN()")
    return b


def write_harmonic(setup: dict, meta: dict, mesh_stats: dict, cfg: dict,
                   analysis: dict = None, ai: int = 1) -> CommBuild:
    """Modal-superposition harmonic response.

    The modal basis is sized automatically: band [0, 1.6 * f_max] so
    truncation above the sweep is acceptable for displacement FRFs.
    """
    import math

    f0 = float(cfg.get("f_min", 20.0))
    f1 = float(cfg.get("f_max", 2000.0))
    nstep = int(cfg.get("n_steps", 200))
    spacing = cfg.get("spacing", "log")
    zeta = float(cfg.get("damping", 0.02))
    if f1 <= f0 or f0 <= 0:
        raise ValueError("Harmonic range must satisfy 0 < f_min < f_max")

    if spacing == "log":
        freqs = [f0 * (f1 / f0) ** (i / (nstep - 1)) for i in range(nstep)]
    else:
        freqs = [f0 + (f1 - f0) * i / (nstep - 1) for i in range(nstep)]

    field_freqs = cfg.get("field_freqs") or []
    field_freqs = sorted({round(float(f), 6) for f in field_freqs if f0 <= float(f) <= f1})

    # Excitation: forces defined in the tree, or rigid-base acceleration.
    base = None
    if cfg.get("excitation") == "base":
        d = cfg.get("base_dir", [0.0, 0.0, 1.0])
        n = math.sqrt(sum(c * c for c in d)) or 1.0
        base = {"dir": [c / n for c in d],
                "accel": float(cfg.get("base_g", 1.0)) * G_MM}   # g -> mm/s^2

    b = CommBuild()
    _prelude(b, setup, meta, mesh_stats, need_probes=True, analysis=analysis, ai=ai)
    fix = _supports(b, analysis, ai)
    load = None
    if base is None:
        load = _loads(b, analysis, ai, meta, harmonic=True)
        if load is None:
            raise ValueError("Harmonic analysis needs a load to excite the structure, "
                             "or set excitation to base acceleration.")
    if not mesh_stats.get("probes"):
        raise ValueError("Harmonic analysis needs at least one probe — "
                         "response is extracted there.")

    modal_cfg = {"band": [0.0, 1.6 * f1]}
    _modal_core(b, setup, modal_cfg, fix)

    def hfreqs(x):
        x.w("ftab = RECU_TABLE(CO=modes, NOM_PARA=('NUME_MODE', 'FREQ'))")
        x.w("IMPR_TABLE(TABLE=ftab, UNITE=38, FORMAT='TABLEAU', SEPARATEUR=',')")
        x.result_files.append((38, "modes.csv"))
    _optional(b, "modal basis table", hfreqs)
    cara_kw = " CARA_ELEM=cara," if getattr(b, "has_beams", False) else ""
    if base is not None:
        d = base["dir"]
        b.w("# Base (support) excitation: CALC_CHAR_SEISME builds the -M.d")
        b.w("# inertial load for a rigid base moving as one body. Response is")
        b.w("# RELATIVE to the base — absolute motion adds the base term back.")
        b.w("fas = CALC_CHAR_SEISME(MATR_MASS=MM, MONO_APPUI='OUI',")
        b.w(f"                       DIRECTION=({_fmt(d[0])}, {_fmt(d[1])}, {_fmt(d[2])}))")
    else:
        b.w(f"vel = CALC_VECT_ELEM(OPTION='CHAR_MECA', CHARGE=({load},),{cara_kw} CHAM_MATER=chmat)")
        b.w("fas = ASSE_VECTEUR(VECT_ELEM=vel, NUME_DDL=nddl)")
    b.w()
    b.w("PROJ_BASE(BASE=modes, STOCKAGE='PLEIN',")
    b.w("          MATR_ASSE_GENE=(_F(MATRICE=CO('KG'), MATR_ASSE=MK),")
    b.w("                          _F(MATRICE=CO('MG'), MATR_ASSE=MM)),")
    b.w("          VECT_ASSE_GENE=(_F(VECTEUR=CO('FG'), VECT_ASSE=fas, TYPE_VECT='FORC'),))")
    b.w()
    vals = ", ".join(_fmt(f) for f in freqs)
    b.w(f"lfr = DEFI_LIST_REEL(VALE=({vals},))")
    b.w()
    coef = base["accel"] if base else 1.0
    b.w("dyng = DYNA_VIBRA(TYPE_CALCUL='HARM', BASE_CALCUL='GENE',")
    b.w("                  MATR_MASS=MG, MATR_RIGI=KG, LIST_FREQ=lfr,")
    b.w(f"                  AMOR_MODAL=_F(AMOR_REDUIT=({_fmt(zeta)},)),")
    b.w(f"                  EXCIT=(_F(VECT_ASSE_GENE=FG, COEF_MULT={_fmt(coef)}),))")
    b.w()

    probes = mesh_stats.get("probes", [])
    unit = 40
    for i, _p in enumerate(probes):
        for c in FRF_COMPONENTS:
            b.w(f"f{i}{c} = RECU_FONCTION(RESU_GENE=dyng, NOM_CHAM='DEPL',")
            b.w(f"    NOM_CMP='{c}', GROUP_NO='PROBE{i + 1}')")
            b.w(f"m{i}{c} = CALC_FONCTION(EXTRACTION=_F(FONCTION=f{i}{c}, PARTIE='MODULE'))")
            b.w(f"p{i}{c} = CALC_FONCTION(EXTRACTION=_F(FONCTION=f{i}{c}, PARTIE='PHASE'))")
            b.w(f"IMPR_FONCTION(FORMAT='TABLEAU', UNITE={unit}, SEPARATEUR=',',")
            b.w(f"    COURBE=(_F(FONCTION=m{i}{c}), _F(FONCTION=p{i}{c})))")
            b.result_files.append((unit, f"frf_p{i + 1}_{c.lower()}.csv"))
            unit += 1
            b.w()

    if field_freqs:
        fv = ", ".join(_fmt(f) for f in field_freqs)
        b.w("dynp = REST_GENE_PHYS(RESU_GENE=dyng, NOM_CHAM='DEPL',")
        b.w(f"                      FREQ=({fv},), INTERPOL='LIN')")
        b.w("IMPR_RESU(FORMAT='MED', UNITE=80, RESU=(")
        b.w("    _F(RESULTAT=dynp, NOM_CHAM='DEPL', PARTIE='REEL'),")
        b.w("    _F(RESULTAT=dynp, NOM_CHAM='DEPL', PARTIE='IMAG')))")
        b.result_files.append((80, "result.med"))
        b.w()

    b.w("FIN()")
    return b


