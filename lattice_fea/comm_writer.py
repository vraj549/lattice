# Bumped when the writer's interpretation of an unchanged setup changes, so
# results computed under the old meaning are marked out of date.
# 1: frictional contact defaults to a bonded solve with a slip check, where it
#    previously always ran nonlinear.
DECK_FORMAT = 1


def active_contacts(setup: dict, mesh_stats: dict) -> list:
    """Contacts whose two face groups actually made it into the mesh."""
    have = set(mesh_stats.get("face_groups") or [])
    out = []
    for i, c in enumerate(setup.get("contacts", []) or []):
        if c.get("suppressed") or not (c.get("faces_a") and c.get("faces_b")):
            continue
        ga, gb = f"CTA{i + 1}", f"CTB{i + 1}"
        if have and not (ga in have and gb in have):
            raise ValueError(
                f"The mesh does not contain the faces of contact "
                f"'{c.get('name', ga)}' — re-mesh before solving.")
        out.append({**c, "index": i + 1, "ga": ga, "gb": gb})
    return out


def solves_linearly(c: dict) -> bool:
    """Whether this interface can be solved without a Newton loop.

    Bonded always can. A **frictional** one can too, when it is checked rather
    than solved: a stuck frictional interface and a bonded one are the same
    constraint, so the bonded solve is exact for a joint that does not slip.
    What makes that honest is testing the premise afterwards from the
    interface tractions — see `slip.py`. If the joint turns out to slip or
    open, the check says so and the nonlinear run is the one to believe.

    Frictionless is never in this set. There is no no-slip premise to
    validate: it slides by definition, and bonded is simply a different
    interface, not a testable stand-in for it.
    """
    kind = c.get("kind", "bonded")
    if kind == "bonded":
        return True
    return kind == "friction" and (c.get("solve") or "linear") == "linear"


def slip_checked(contacts: list) -> list:
    """Frictional interfaces being solved bonded, which owe a slip check."""
    return [c for c in contacts
            if c.get("kind") == "friction" and solves_linearly(c)]


def needs_nonlinear(contacts: list) -> bool:
    """Sliding or separating contact is a nonlinear problem.

    Whether two surfaces are touching is part of the answer, not part of the
    question, so the stiffness depends on the solution and MECA_STATIQUE
    cannot be used — unless the answer is asserted in advance and checked
    afterwards, which is what `solves_linearly` allows for friction.
    """
    return any(not solves_linearly(c) for c in contacts)


def _contact_defi(b: CommBuild, contacts: list) -> "str|None":
    """DEFI_CONTACT over every non-bonded interface.

    CONTINUE formulation: the augmented-Lagrangian one, which is the robust
    default for solid-on-solid in code_aster. Bonded pairs are not listed —
    they are handled as LIAISON_MAIL ties, which stay linear and are exact.
    """
    zones = [c for c in contacts if not solves_linearly(c)]
    if not zones:
        return None
    b.w("# Contact. Master is the first-listed side; the finer side should be")
    b.w("# the slave, which is why the UI lets you swap them.")
    b.w("contact = DEFI_CONTACT(MODELE=model, FORMULATION='CONTINUE',")
    b.w("                       ALGO_RESO_GEOM='NEWTON',")
    b.w("                       ZONE=(")
    for c in zones:
        kind = c.get("kind")
        b.w(f"    _F(GROUP_MA_MAIT='{c['ga']}', GROUP_MA_ESCL='{c['gb']}',")
        if kind == "friction":
            mu = float(c.get("mu") or 0.2)
            b.w("       ALGO_CONT='STANDARD', COEF_CONT=100.0,")
            b.w(f"       FROTTEMENT='COULOMB', COULOMB={_fmt(mu)},")
            b.w("       ALGO_FROT='STANDARD', COEF_FROT=100.0,")
        elif kind == "noseparation":
            # glued in the normal direction once closed, free to slide
            b.w("       ALGO_CONT='STANDARD', COEF_CONT=100.0,")
            b.w("       CONTACT_INIT='OUI',")
        else:                                   # frictionless
            b.w("       ALGO_CONT='STANDARD', COEF_CONT=100.0,")
        b.w("       ),")
    b.w("))")
    b.w()
    return "contact"


def _ramp(b: CommBuild, n_steps: int, preload: bool, load: bool = True) -> None:
    """Time discretisation.

    Two ramps when preload and an external load are both present: the bolts
    are tightened first with nothing else applied, then the load is applied on
    top. Applying both at once would let the joint be pushed open before it
    was ever clamped, which is not the sequence the hardware sees and can fail
    to converge.

    With only one of the two there is nothing to sequence, so it stays a
    single ramp — that is the preload calibration run, and it should not pay
    for a second ramp that applies nothing.
    """
    two = preload and load
    b.w(f"tlist = DEFI_LIST_REEL(DEBUT=0.0, INTERVALLE=(")
    if two:
        b.w(f"    _F(JUSQU_A=1.0, NOMBRE={max(2, n_steps // 2)}),")
        b.w(f"    _F(JUSQU_A=2.0, NOMBRE={max(2, n_steps)}),")
    else:
        b.w(f"    _F(JUSQU_A=1.0, NOMBRE={max(2, n_steps)}),")
    b.w("))")
    b.w("tstep = DEFI_LIST_INST(METHODE='AUTO',")
    b.w("                       DEFI_LIST=_F(LIST_INST=tlist),")
    b.w("                       ECHEC=_F(SUBD_METHODE='MANUEL', SUBD_PAS=4,")
    b.w("                                SUBD_NIVEAU=4))")
    if two:
        b.w("# bolts tighten over [0,1] and hold; external load ramps over [1,2]")
        b.w("fpre = DEFI_FONCTION(NOM_PARA='INST', PROL_DROITE='CONSTANT',")
        b.w("                     VALE=(0.0, 0.0, 1.0, 1.0, 2.0, 1.0))")
        b.w("fext = DEFI_FONCTION(NOM_PARA='INST', PROL_DROITE='CONSTANT',")
        b.w("                     VALE=(0.0, 0.0, 1.0, 0.0, 2.0, 1.0))")
    else:
        name = "fpre" if preload else "fext"
        b.w(f"{name} = DEFI_FONCTION(NOM_PARA='INST', PROL_DROITE='CONSTANT',")
        b.w("                     VALE=(0.0, 0.0, 1.0, 1.0))")
    b.w(f"# ramp stops: {'0.0, 1.0, 2.0' if two else '0.0, 1.0'}")
    b.w()


def write_static(setup: dict, meta: dict, mesh_stats: dict, cfg: dict,
                 analysis: dict = None, ai: int = 1, **kw) -> CommBuild:
    """Static solve.

    `calibration=True` writes the preload-only deck that measures what the
    requested preload actually produces in this joint: same mesh, supports,
    constraints and contact, but no external load and no field output — the
    bolt end forces are all it is read for, and skipping stress recovery and
    the MED write is most of what makes the extra solve affordable.

    `preload_scale` is the per-bolt correction that calibration returns.
    """
    calibration = bool(kw.get("calibration"))
    b = CommBuild()
    _prelude(b, setup, meta, mesh_stats, need_probes=False, analysis=analysis, ai=ai)
    fix = _supports(b, analysis, ai)
    load = None if calibration else _loads(b, analysis, ai, meta)
    preload = _preload_charge(b, kw.get("preload_scale"))
    if load is None and preload is None:
        raise ValueError("Static analysis needs at least one load (force, pressure, gravity, or bolt preload).")

    contacts = active_contacts(setup, mesh_stats)
    nonlinear = needs_nonlinear(contacts)
    if nonlinear:
        _write_nonlinear_static(b, fix, load, preload, contacts, analysis)
    else:
        charges = ([fix] + b.constraint_charges + ([load] if load else [])
                   + ([preload] if preload else []))
        excit = ", ".join(f"_F(CHARGE={c})" for c in charges)
        b.w("res = MECA_STATIQUE(MODELE=model, CHAM_MATER=chmat,")
        b.w(f"                    EXCIT=({excit},),{_cara_arg(b)}")
        b.w("                    SOLVEUR=_F(METHODE='MUMPS'))")
        b.w()
    if calibration:
        _bolt_forces_out(b, "res")
        b.w("FIN()")
        return b
    vol_restrict = ""
    if getattr(b, "has_beams", False):
        # stress recovery is a solid-element concept; beams get EFGE below
        vol_restrict = "                 GROUP_MA=%s,\n" % _group_tuple(
            ["V%d" % s["tag"] for s in meta.get("solids", [])])
    b.w(f"res = CALC_CHAMP(reuse=res, RESULTAT=res,{_cara_arg(b)}")
    if vol_restrict:
        b.w(vol_restrict.rstrip("\n"))
    b.w("                 CONTRAINTE=('SIGM_NOEU',),")
    b.w("                 CRITERES=('SIEQ_NOEU',),")
    b.w("                 FORCE=('REAC_NODA',))")
    b.w()
    vol_groups = _group_tuple(["V%d" % s["tag"] for s in meta.get("solids", [])])
    b.w("IMPR_RESU(FORMAT='MED', UNITE=80, RESU=_F(")
    b.w("    RESULTAT=res, NOM_CHAM=('DEPL', 'SIEQ_NOEU', 'SIGM_NOEU'),")
    b.w(f"    GROUP_MA={vol_groups}))")
    b.result_files.append((80, "result.med"))
    b.w()
    _bolt_forces_out(b, "res")
    _slip_check_out(b, contacts)
    groups = _support_groups(analysis, ai)

    def reactions(x):
        x.w("rtab = POST_RELEVE_T(ACTION=_F(INTITULE='REACTIONS', OPERATION='EXTRACTION',")
        x.w("                               RESULTANTE=('DX', 'DY', 'DZ'),")
        x.w("                               RESULTAT=res, NOM_CHAM='REAC_NODA',")
        x.w(f"                               GROUP_NO={_group_tuple(groups)}))")
        x.w("IMPR_TABLE(TABLE=rtab, UNITE=37, FORMAT='TABLEAU', SEPARATEUR=',')")
        x.result_files.append((37, "tables.txt"))
    _optional(b, "reaction forces", reactions)

    b.w("FIN()")
    return b


def _modal_core(b: CommBuild, setup: dict, cfg: dict, fix: str) -> None:
    """ASSEMBLAGE + CALC_MODES; leaves `modes`, `MK`, `MM`, `nddl` defined.
    Bolt spiders and ties are constraint charges: they belong in the
    assembled operators so beams and glued interfaces carry stiffness in
    modal/harmonic too. Preload does not enter (linear, no stress stiffening)."""
    charges = ", ".join([fix] + b.constraint_charges)
    b.w(f"ASSEMBLAGE(MODELE=model, CHAM_MATER=chmat, CHARGE=({charges},),")
    if getattr(b, "has_beams", False):
        b.w("           CARA_ELEM=cara,")
    b.w("           NUME_DDL=CO('nddl'),")
    b.w("           MATR_ASSE=(_F(MATRICE=CO('MK'), OPTION='RIGI_MECA'),")
    b.w("                      _F(MATRICE=CO('MM'), OPTION='MASS_MECA')))")
    b.w()
    band = cfg.get("band")
    if band:
        b.w("modes = CALC_MODES(MATR_RIGI=MK, MATR_MASS=MM, OPTION='BANDE',")
        b.w(f"                   CALC_FREQ=_F(FREQ=({_fmt(band[0])}, {_fmt(band[1])})),")
    else:
        n = int(cfg.get("n_modes", 10))
        b.w("modes = CALC_MODES(MATR_RIGI=MK, MATR_MASS=MM, OPTION='PLUS_PETITE',")
        b.w(f"                   CALC_FREQ=_F(NMAX_FREQ={n}),")
    b.w("                   SOLVEUR_MODAL=_F(METHODE='SORENSEN'),")
    b.w("                   SOLVEUR=_F(METHODE='MUMPS'),")
    b.w("                   VERI_MODE=_F(STOP_ERREUR='NON'))")
    b.w()


def _optional(b: CommBuild, comment: str, body) -> None:
    """Emit a block that must never abort the run.

    A .comm is executed as Python, so a catchable code_aster <EXCEPTION>
    (a wrong NOM_PARA, a parameter a given version doesn't publish) can be
    contained. Without this, one unavailable table throws away results that
    were already computed — which is exactly what happened to the first real
    modal run.
    """
    b.w(f"# optional: {comment}")
    b.w("try:")
    inner = CommBuild()
    body(inner)
    for line in inner.lines:
        b.w(f"    {line}" if line else "")
    b.result_files.extend(inner.result_files)
    b.w("except Exception as _e:")
    b.w(f"    print('Lattice: skipped {comment} —', _e)")
    b.w()



def _write_nonlinear_static(b: CommBuild, fix, load, preload, contacts, analysis):
    """Incremental static with contact.

    Small strain, small displacement (the default PETIT deformation): the
    nonlinearity here is the contact status, not the geometry. Anything that
    actually needs large rotation is outside what this tool claims to do.
    """
    cvar = _contact_defi(b, contacts)
    cfg = (analysis or {}).get("config", {}) or {}
    _ramp(b, int(cfg.get("contact_steps") or 8),
          preload is not None, load is not None)

    excit = [f"_F(CHARGE={fix})"] + [f"_F(CHARGE={c})" for c in b.constraint_charges]
    if preload:
        excit.append(f"_F(CHARGE={preload}, FONC_MULT=fpre)"
                     if preload else "")
    if load:
        excit.append(f"_F(CHARGE={load}, FONC_MULT=fext)")
    excit = [e for e in excit if e]

    b.w("res = STAT_NON_LINE(MODELE=model, CHAM_MATER=chmat,")
    b.w(f"                    EXCIT=({', '.join(excit)},),{_cara_arg(b)}")
    if cvar:
        b.w(f"                    CONTACT={cvar},")
    b.w("                    COMPORTEMENT=_F(RELATION='ELAS', DEFORMATION='PETIT'),")
    b.w("                    INCREMENT=_F(LIST_INST=tstep),")
    b.w("                    NEWTON=_F(REAC_ITER=1),")
    b.w("                    CONVERGENCE=_F(RESI_GLOB_RELA=1e-6, ITER_GLOB_MAXI=30),")
    b.w("                    SOLVEUR=_F(METHODE='MUMPS'))")
    b.w()

def write_modal(setup: dict, meta: dict, mesh_stats: dict, cfg: dict,
                analysis: dict = None, ai: int = 1, **kw) -> CommBuild:
    b = CommBuild()
    _prelude(b, setup, meta, mesh_stats, need_probes=False, analysis=analysis, ai=ai)
    fix = _supports(b, analysis, ai)
    _modal_core(b, setup, cfg, fix)

    # Mode shapes FIRST: IMPR_RESU is the most stable command here and the
    # result is the expensive one. Tables come after, each individually
    # non-fatal, so a version quirk in a table can't discard the modes.
    b.w("IMPR_RESU(FORMAT='MED', UNITE=80, RESU=_F(RESULTAT=modes, NOM_CHAM='DEPL'))")
    b.result_files.append((80, "result.med"))
    b.w()

    # MODE_MECA numbers modes with NUME_MODE (NUME_ORDRE does not exist on it)
    def freqs(x):
        x.w("ftab = RECU_TABLE(CO=modes, NOM_PARA=('NUME_MODE', 'FREQ'))")
        x.w("IMPR_TABLE(TABLE=ftab, UNITE=38, FORMAT='TABLEAU', SEPARATEUR=',')")
        x.result_files.append((38, "modes.csv"))
    _optional(b, "frequency table", freqs)

    def mass(x):
        x.w("mtab = POST_ELEM(MODELE=model, CHAM_MATER=chmat, MASS_INER=_F(TOUT='OUI'))")
        x.w("IMPR_TABLE(TABLE=mtab, UNITE=37, FORMAT='TABLEAU', SEPARATEUR=',')")
        x.result_files.append((37, "tables.txt"))
    _optional(b, "model mass", mass)

    def part(x):
        x.w("ptab = RECU_TABLE(CO=modes, NOM_PARA=('NUME_MODE', 'FREQ', 'MASS_GENE',")
        x.w("                  'MASS_EFFE_UN_DX', 'MASS_EFFE_UN_DY', 'MASS_EFFE_UN_DZ'))")
        x.w("IMPR_TABLE(TABLE=ptab, UNITE=39, FORMAT='TABLEAU', SEPARATEUR=',')")
        x.result_files.append((39, "participation.csv"))
    _optional(b, "effective mass table", part)

    b.w("FIN()")
    return b


def write_harmonic(setup: dict, meta: dict, mesh_stats: dict, cfg: dict,
                   analysis: dict = None, ai: int = 1, **kw) -> CommBuild:
    """Modal-superposition harmonic response.

    The modal basis is sized automatically: band [0, 1.6 * f_max] so
    truncation above the sweep is acceptable for displacement FRFs.
    """

    f0 = float(cfg.get("f_min", 20.0))
    f1 = float(cfg.get("f_max", 2000.0))
    nstep = int(cfg.get("n_steps", 200))
    spacing = cfg.get("spacing", "log")
    zeta = float(cfg.get("damping", 0.02))
    if f1 <= f0 or f0 <= 0:
        raise ValueError("Harmonic range must satisfy 0 < f_min < f_max")

    if spacing == "log":
        freqs = [f0 * (f1 / f0) ** (i / (nstep - 1)) for i in range(nstep)]
    else:
        freqs = [f0 + (f1 - f0) * i / (nstep - 1) for i in range(nstep)]

    field_freqs = cfg.get("field_freqs") or []
    field_freqs = sorted({round(float(f), 6) for f in field_freqs if f0 <= float(f) <= f1})

    # Excitation: forces defined in the tree, or rigid-base acceleration.
    base = None
    if cfg.get("excitation") == "base":
        d = cfg.get("base_dir", [0.0, 0.0, 1.0])
        n = math.sqrt(sum(c * c for c in d)) or 1.0
        base = {"dir": [c / n for c in d],
                "accel": float(cfg.get("base_g", 1.0)) * G_MM}   # g -> mm/s^2

    b = CommBuild()
    _prelude(b, setup, meta, mesh_stats, need_probes=True, analysis=analysis, ai=ai)
    fix = _supports(b, analysis, ai)
    load = None
    if base is None:
        load = _loads(b, analysis, ai, meta, harmonic=True)
        if load is None:
            raise ValueError("Harmonic analysis needs a load to excite the structure, "
                             "or set excitation to base acceleration.")
    if not mesh_stats.get("probes"):
        raise ValueError("Harmonic analysis needs at least one probe — "
                         "response is extracted there.")

    modal_cfg = {"band": [0.0, 1.6 * f1]}
    _modal_core(b, setup, modal_cfg, fix)

    def hfreqs(x):
        x.w("ftab = RECU_TABLE(CO=modes, NOM_PARA=('NUME_MODE', 'FREQ'))")
        x.w("IMPR_TABLE(TABLE=ftab, UNITE=38, FORMAT='TABLEAU', SEPARATEUR=',')")
        x.result_files.append((38, "modes.csv"))
    _optional(b, "modal basis table", hfreqs)
    cara_kw = " CARA_ELEM=cara," if getattr(b, "has_beams", False) else ""
    if base is not None:
        d = base["dir"]
        b.w("# Base (support) excitation: CALC_CHAR_SEISME builds the -M.d")
        b.w("# inertial load for a rigid base moving as one body. Response is")
        b.w("# RELATIVE to the base — absolute motion adds the base term back.")
        b.w("fas = CALC_CHAR_SEISME(MATR_MASS=MM, MONO_APPUI='OUI',")
        b.w(f"                       DIRECTION=({_fmt(d[0])}, {_fmt(d[1])}, {_fmt(d[2])}))")
    else:
        b.w(f"vel = CALC_VECT_ELEM(OPTION='CHAR_MECA', CHARGE=({load},),{cara_kw} CHAM_MATER=chmat)")
        b.w("fas = ASSE_VECTEUR(VECT_ELEM=vel, NUME_DDL=nddl)")
    b.w()
    b.w("PROJ_BASE(BASE=modes, STOCKAGE='PLEIN',")
    b.w("          MATR_ASSE_GENE=(_F(MATRICE=CO('KG'), MATR_ASSE=MK),")
    b.w("                          _F(MATRICE=CO('MG'), MATR_ASSE=MM)),")
    b.w("          VECT_ASSE_GENE=(_F(VECTEUR=CO('FG'), VECT_ASSE=fas, TYPE_VECT='FORC'),))")
    b.w()
    vals = ", ".join(_fmt(f) for f in freqs)
    b.w(f"lfr = DEFI_LIST_REEL(VALE=({vals},))")
    b.w()
    coef = base["accel"] if base else 1.0
    b.w("dyng = DYNA_VIBRA(TYPE_CALCUL='HARM', BASE_CALCUL='GENE',")
    b.w("                  MATR_MASS=MG, MATR_RIGI=KG, LIST_FREQ=lfr,")
    b.w(f"                  AMOR_MODAL=_F(AMOR_REDUIT=({_fmt(zeta)},)),")
    b.w(f"                  EXCIT=(_F(VECT_ASSE_GENE=FG, COEF_MULT={_fmt(coef)}),))")
    b.w()

    probes = mesh_stats.get("probes", [])
    unit = 40
    for i, _p in enumerate(probes):
        for c in FRF_COMPONENTS:
            b.w(f"f{i}{c} = RECU_FONCTION(RESU_GENE=dyng, NOM_CHAM='DEPL',")
            b.w(f"    NOM_CMP='{c}', GROUP_NO='PROBE{i + 1}')")
            b.w(f"m{i}{c} = CALC_FONCTION(EXTRACTION=_F(FONCTION=f{i}{c}, PARTIE='MODULE'))")
            b.w(f"p{i}{c} = CALC_FONCTION(EXTRACTION=_F(FONCTION=f{i}{c}, PARTIE='PHASE'))")
            b.w(f"IMPR_FONCTION(FORMAT='TABLEAU', UNITE={unit}, SEPARATEUR=',',")
            b.w(f"    COURBE=(_F(FONCTION=m{i}{c}), _F(FONCTION=p{i}{c})))")
            b.result_files.append((unit, f"frf_p{i + 1}_{c.lower()}.csv"))
            unit += 1
            b.w()

    if field_freqs:
        fv = ", ".join(_fmt(f) for f in field_freqs)
        b.w("dynp = REST_GENE_PHYS(RESU_GENE=dyng, NOM_CHAM='DEPL',")
        b.w(f"                      FREQ=({fv},), INTERPOL='LIN')")
        b.w("IMPR_RESU(FORMAT='MED', UNITE=80, RESU=(")
        b.w("    _F(RESULTAT=dynp, NOM_CHAM='DEPL', PARTIE='REEL'),")
        b.w("    _F(RESULTAT=dynp, NOM_CHAM='DEPL', PARTIE='IMAG')))")
        b.result_files.append((80, "result.med"))
        b.w()

    b.w("FIN()")
    return b


