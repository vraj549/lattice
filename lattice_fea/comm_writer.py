def write_random(setup: dict, meta: dict, mesh_stats: dict, cfg: dict,
                 analysis: dict = None, ai: int = 1, **kw) -> CommBuild:
    """Random vibration = a unit-g base sweep spanning the input spectrum.

    Driving with exactly 1 g makes the exported FRF read directly as
    transmissibility, and the response PSD is then |T|^2 * PSD_in, integrated
    in random_vib.py. That keeps the solver side identical to the harmonic
    case which is already proven, instead of relying on a separate random
    operator chain.
    """
    spec = cfg.get("spec") or []
    pts = sorted((float(a), float(b)) for a, b in spec if float(a) > 0)
    if len(pts) < 2:
        raise ValueError("Random vibration needs at least two PSD breakpoints.")
    f0, f1 = pts[0][0], pts[-1][0]
    hcfg = {
        **cfg,
        "excitation": "base",
        "base_g": 1.0,                      # unit input => transmissibility
        "f_min": f0, "f_max": f1,
        "spacing": "log",
        "n_steps": int(cfg.get("n_steps", 600)),
        "field_freqs": cfg.get("field_freqs") or [],
    }
    return write_harmonic(setup, meta, mesh_stats, hcfg, analysis, ai)


def write_shock(setup: dict, meta: dict, mesh_stats: dict, cfg: dict,
                analysis: dict = None, ai: int = 1, **kw) -> CommBuild:
    """Shock response spectrum — the modal deck, plus what the spectrum needs.

    An SRS gives peak response per frequency with no phase and no time, so
    there is nothing for the solver to integrate: the answer is a combination
    over the modal basis. The solve is therefore exactly the modal one, which
    is already proven, and the spectrum arithmetic happens in `shock.py` where
    it is unit-tested — the same division `random_vib` uses, and for the same
    reason.

    What is added over `write_modal` is per-mode extraction at the probes and
    at the bolt beams, so mode shapes can be weighted and combined into peak
    displacements and peak bolt loads. Both are optional blocks: neither may
    cost the run its modes.
    """
    n_modes = int(cfg.get("n_modes") or 0)
    band = cfg.get("band")
    mcfg = {"band": band} if band else {"n_modes": n_modes or 30}
    probes = mesh_stats.get("probes", [])

    b = CommBuild()
    _prelude(b, setup, meta, mesh_stats, need_probes=bool(probes),
             analysis=analysis, ai=ai)
    fix = _supports(b, analysis, ai)
    if not fix:
        raise ValueError("Shock analysis needs a support — the spectrum is "
                         "applied at the restrained base.")
    _modal_core(b, setup, mcfg, fix)

    b.w("IMPR_RESU(FORMAT='MED', UNITE=80, RESU=_F(RESULTAT=modes, NOM_CHAM='DEPL'))")
    b.result_files.append((80, "result.med"))
    b.w()

    def freqs(x):
        x.w("ftab = RECU_TABLE(CO=modes, NOM_PARA=('NUME_MODE', 'FREQ'))")
        x.w("IMPR_TABLE(TABLE=ftab, UNITE=38, FORMAT='TABLEAU', SEPARATEUR=',')")
        x.result_files.append((38, "modes.csv"))
    _optional(b, "frequency table", freqs)

    # Total mass turns the unitary effective masses into real ones, which is
    # what makes the interface force a force. Without it there is no shock
    # answer at all, only fractions.
    def mass(x):
        x.w("mtab = POST_ELEM(MODELE=model, CHAM_MATER=chmat, MASS_INER=_F(TOUT='OUI'))")
        x.w("IMPR_TABLE(TABLE=mtab, UNITE=37, FORMAT='TABLEAU', SEPARATEUR=',')")
        x.result_files.append((37, "tables.txt"))
    _optional(b, "model mass", mass)

    def part(x):
        x.w("ptab = RECU_TABLE(CO=modes, NOM_PARA=('NUME_MODE', 'FREQ', 'MASS_GENE',")
        x.w("                  'MASS_EFFE_UN_DX', 'MASS_EFFE_UN_DY', 'MASS_EFFE_UN_DZ'))")
        x.w("IMPR_TABLE(TABLE=ptab, UNITE=39, FORMAT='TABLEAU', SEPARATEUR=',')")
        x.result_files.append((39, "participation.csv"))
    _optional(b, "effective mass table", part)

    if probes:
        def probe_shapes(x):
            for i, _p in enumerate(probes):
                x.w(f"sp{i} = POST_RELEVE_T(ACTION=_F(")
                x.w(f"    INTITULE='PROBE{i + 1}', OPERATION='EXTRACTION',")
                x.w(f"    RESULTAT=modes, NOM_CHAM='DEPL', TOUT_ORDRE='OUI',")
                x.w(f"    GROUP_NO='PROBE{i + 1}', NOM_CMP=('DX', 'DY', 'DZ')))")
                x.w(f"IMPR_TABLE(TABLE=sp{i}, UNITE=36, FORMAT='TABLEAU', "
                    f"SEPARATEUR=',')")
            x.result_files.append((36, "mode_probes.csv"))
        _optional(b, "mode shapes at probes", probe_shapes)

    if getattr(b, "has_bolts", False):
        beam_groups = _group_tuple([f"BOLT{br['index']}" for br in b.bolts])

        def bolt_modes(x):
            x.w("modes = CALC_CHAMP(reuse=modes, RESULTAT=modes,")
            x.w(f"                   CARA_ELEM=cara, GROUP_MA={beam_groups},")
            x.w("                   CONTRAINTE=('EFGE_ELNO',))")
            for br in b.bolts:
                for side in ("A", "B"):
                    x.w(f"mb{br['index']}{side} = POST_RELEVE_T(ACTION=_F(")
                    x.w(f"    INTITULE='BOLT{br['index']}_{side}', "
                        f"OPERATION='EXTRACTION',")
                    x.w(f"    RESULTAT=modes, NOM_CHAM='EFGE_ELNO', "
                        f"TOUT_ORDRE='OUI',")
                    x.w(f"    GROUP_NO='BN{br['index']}{side}', TOUT_CMP='OUI'))")
                    x.w(f"IMPR_TABLE(TABLE=mb{br['index']}{side}, UNITE=35, "
                        f"FORMAT='TABLEAU', SEPARATEUR=',')")
            x.result_files.append((35, "mode_bolts.csv"))
        _optional(b, "bolt forces per mode", bolt_modes)

    b.w("FIN()")
    return b


WRITERS = {"static": write_static, "modal": write_modal,
           "harmonic": write_harmonic, "random": write_random,
           "shock": write_shock}


def bolt_area(cfg: dict) -> float:
    """Cross-section of a bolt shank, in mm^2.

    The TENSILE STRESS AREA, not the circle on the major diameter: a bolt
    carries axial load through its thread, and on the small sizes the gap is
    not a rounding detail — an M1.6 modelled on its nominal 1.6 mm shank comes
    out 58 % stiffer than the real screw, which changes how the joint shares
    load with the parts around it.

    Both the beam section and the preload pre-strain must use this same
    number. Preload is applied as eps = -F / (E * A) so that the resulting
    beam force is exactly -F; if the section were sized on a different area,
    every bolt force in the model would be scaled by the ratio of the two.
    """
    a = cfg.get("as_mm2")
    if a:
        return float(a)
    d = float(cfg.get("d_mm") or 8.0)
    return math.pi * (d / 2.0) ** 2


def required_face_groups(analysis: dict, ai: int) -> list:
    """Mesh groups this analysis's .comm will reference."""
    need = [group_name("SUP", ai, i + 1)
            for i, s in enumerate(analysis.get("supports", [])) if s.get("faces")]
    need += [group_name("LOA", ai, i + 1)
             for i, l in enumerate(analysis.get("loads", []))
             if l.get("type") in ("force", "pressure", "remote") and l.get("faces")]
    return need


def check_mesh_current(analysis: dict, ai: int, mesh_stats: dict) -> None:
    """Refuse to build a deck that references groups the mesh does not contain.

    The mesh records exactly which groups it wrote. If a support was added
    after meshing — or the naming scheme changed between versions — the solver
    would run for minutes and then abort with a group-not-found error deep in
    the log. Catch it here instead, for free.
    """
    from .meshing import MESH_FORMAT
    if (mesh_stats.get("mesh_format") or 0) < MESH_FORMAT:
        raise ValueError(
            "This mesh was written by an earlier version of Lattice and is no "
            "longer trustworthy — bolt beams spanned half the clamped length, "
            "and group records could contain node entities. Re-mesh, then run "
            "again.")
    have = set(mesh_stats.get("face_groups") or [])
    if not have:
        return                                  # meshed before groups were recorded
    missing = [g for g in required_face_groups(analysis, ai) if g not in have]
    if missing:
        raise ValueError(
            f"The mesh does not contain {', '.join(missing)} — it is older than "
            "the current boundary conditions. Re-mesh, then run again. "
            f"(mesh has: {', '.join(sorted(have)) or 'no face groups'})")


def build_run(analysis: dict, setup: dict, meta: dict, mesh_stats: dict,
              solver_cfg, **kw) -> "tuple[str, str]":
    """Returns (comm_text, export_text).

    `calibration` / `preload_scale` are forwarded to the writer; only the
    static writer acts on them (preload exists nowhere else).
    """
    atype = analysis.get("type")
    if atype not in WRITERS:
        raise ValueError(f"Unknown analysis type: {atype}")
    if len(mesh_stats.get("probes", [])) > 6:
        raise ValueError("At most 6 probes are supported (logical unit budget).")
    ai = 1 + next((i for i, a in enumerate(setup.get("analyses", []))
                   if a.get("id") == analysis.get("id")), 0)
    check_mesh_current(analysis, ai, mesh_stats)
    b = WRITERS[atype](setup, meta, mesh_stats, analysis.get("config", {}),
                       analysis, ai, **kw)

    exp = [
        "P actions make_etude",
        f"P memory_limit {int(solver_cfg.memory_mb)}",
        f"P time_limit {int(solver_cfg.time_limit_s)}",
        f"P ncpus {int(solver_cfg.ncpus)}",
        "P mpi_nbcpu 1",
        "F comm run.comm D 1",
        "F libr mesh.unv D 19",
    ]
    seen = set()
    for unit, fname in b.result_files:
        if unit in seen:
            continue
        seen.add(unit)
        exp.append(f"F libr {fname} R {unit}")
    exp.append("F mess run.mess R 6")
    return b.text(), "\n".join(exp) + "\n"
