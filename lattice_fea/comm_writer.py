"""Generate code_aster command (.comm) and run_aster export files.

Unit convention (mm-t-s): E [MPa], rho [t/mm^3], force [N], pressure [MPa],
gravity [mm/s^2], frequency [Hz].

Logical unit map (run_aster copies fort.<n> back for R entries):
  19  mesh.unv          (D)   IDEAS mesh from gmsh
  80  result.med        (R)   fields
  37  tables.txt        (R)   mass / reactions (block CSV)
  38  modes.csv         (R)   frequency table
  39  participation.csv (R)   effective-mass table
  40+ frf_p<i>_<c>.csv  (R)   FRF module+phase per probe component

Ordering and failure policy: the expensive result (the MED) is written FIRST,
because it is produced by IMPR_RESU, the most version-stable command here.
Every table afterwards is emitted inside `try/except` via _optional(), since a
.comm executes as Python and code_aster <EXCEPTION> errors are catchable.

This is deliberate. The first real modal run computed all ten modes and then
threw them away, because a table used NOM_PARA='NUME_ORDRE' (a MODE_MECA
publishes NUME_MODE) and the abort happened before the MED was written.
No single table may ever discard a completed solve again.
"""
from __future__ import annotations

import math

from .materials import to_solver_units
from .meshing import group_name

G_MM = 9810.0  # standard gravity, mm/s^2

FRF_COMPONENTS = ("DX", "DY", "DZ")


def _fmt(x) -> str:
    return repr(float(x))


def _group_tuple(names) -> str:
    inner = ", ".join(f"'{n}'" for n in names)
    return f"({inner},)"


class CommBuild:
    def __init__(self):
        self.lines = []
        self.result_files = []   # (unit, filename)

    def w(self, s=""):
        self.lines.append(s)

    def text(self):
        return "\n".join(self.lines) + "\n"


def _env_sphere(b: CommBuild, name: str, xyz, r: float) -> None:
    b.w(f"mesh = DEFI_GROUP(reuse=mesh, MAILLAGE=mesh, CREA_GROUP_NO=_F(")
    b.w(f"    NOM='{name}', OPTION='ENV_SPHERE',")
    b.w(f"    POINT=({_fmt(xyz[0])}, {_fmt(xyz[1])}, {_fmt(xyz[2])}),")
    b.w(f"    RAYON={_fmt(r)}, PRECISION={_fmt(r)}))")


def _prelude(b: CommBuild, setup: dict, meta: dict, mesh_stats: dict,
             need_probes: bool, analysis: dict = None, ai: int = 1) -> None:
    bolts = _active_bolts(setup, mesh_stats)
    remotes = _active_remotes(analysis or {}, ai, mesh_stats)

    b.w("# Generated by Lattice — do not edit while a run is active")
    b.w("DEBUT(LANG='EN')")
    b.w()
    b.w("mesh = LIRE_MAILLAGE(FORMAT='IDEAS', UNITE=19)")
    b.w()
    b.w("mesh = DEFI_GROUP(reuse=mesh, MAILLAGE=mesh,")
    b.w("                  CREA_GROUP_NO=_F(TOUT_GROUP_MA='OUI'))")

    if need_probes:
        for i, p in enumerate(mesh_stats.get("probes", [])):
            r = max(p.get("snap_dist", 0.0) * 1e-3, 1e-6)
            _env_sphere(b, f"PROBE{i + 1}", p["node_xyz"], r)
    # bolt end nodes / remote points: exact coordinates from mesh time
    for br in bolts:
        _env_sphere(b, f"BN{br['index']}A", br["end_a"], 1e-5)
        _env_sphere(b, f"BN{br['index']}B", br["end_b"], 1e-5)
    for rr in remotes:
        _env_sphere(b, group_name("RPN", rr.get("analysis_index", ai),
                                  rr["load_index"]), rr["node"], 1e-5)
    b.w()

    beam_groups = ([f"BOLT{br['index']}" for br in bolts]
                   + [rr.get("group") or group_name("RPT", rr.get("analysis_index", ai),
                                                    rr["load_index"]) for rr in remotes])

    # model: explicit group lists — beams and solids carry different
    # modelisations, so TOUT='OUI' is no longer possible with beams present
    vol_groups = [f"V{s['tag']}" for s in meta.get("solids", [])]
    face_groups = mesh_stats.get("face_groups", [])
    if beam_groups:
        g3d = _group_tuple(vol_groups + list(face_groups))
        b.w("model = AFFE_MODELE(MAILLAGE=mesh, AFFE=(")
        b.w(f"    _F(GROUP_MA={g3d}, PHENOMENE='MECANIQUE', MODELISATION='3D'),")
        b.w(f"    _F(GROUP_MA={_group_tuple(beam_groups)}, PHENOMENE='MECANIQUE', MODELISATION='POU_D_T'),")
        b.w("))")
    else:
        b.w("model = AFFE_MODELE(MAILLAGE=mesh,")
        b.w("                    AFFE=_F(TOUT='OUI', PHENOMENE='MECANIQUE', MODELISATION='3D'))")
    b.w()

    # materials
    mats = {m["id"]: m for m in setup.get("materials", [])}
    assign = setup.get("assignments", {})
    mat_vars = {}
    for k, mid in sorted(assign.items()):
        if mid not in mats:
            raise ValueError(f"Solid {k} references unknown material '{mid}'")
        if mid not in mat_vars:
            u = to_solver_units(mats[mid])
            var = f"mat{len(mat_vars) + 1}"
            mat_vars[mid] = var
            b.w(f"{var} = DEFI_MATERIAU(ELAS=_F(E={_fmt(u['E'])}, NU={_fmt(u['NU'])}, RHO={_fmt(u['RHO'])}))")
    affes = []
    for k, mid in sorted(assign.items()):
        affes.append(f"_F(GROUP_MA=('V{int(k)}',), MATER={mat_vars[mid]})")
    if not affes:
        raise ValueError("No material assignments — assign a material to every solid before solving.")
    for br in bolts:
        cfg = br["cfg"]
        E = float(cfg.get("E_GPa", 210.0)) * 1000.0
        b.w(f"matb{br['index']} = DEFI_MATERIAU(ELAS=_F(E={_fmt(E)}, NU=0.3, RHO=7.85e-09))")
        affes.append(f"_F(GROUP_MA=('BOLT{br['index']}',), MATER=matb{br['index']})")
    if remotes:
        b.w("matrp = DEFI_MATERIAU(ELAS=_F(E=210000.0, NU=0.3, RHO=7.85e-09))")
        for rr in remotes:
            affes.append("_F(GROUP_MA=('%s',), MATER=matrp)" % (
                rr.get("group") or group_name("RPT", rr.get("analysis_index", ai), rr["load_index"])))
    b.w()
    b.w("chmat = AFFE_MATERIAU(MAILLAGE=mesh, AFFE=(")
    for a in affes:
        b.w(f"    {a},")
    b.w("))")
    b.w()

    # beam sections + spiders
    if beam_groups:
        b.w("cara = AFFE_CARA_ELEM(MODELE=model, POUTRE=(")
        for br in bolts:
            r = math.sqrt(bolt_area(br["cfg"]) / math.pi)
            b.w(f"    _F(GROUP_MA=('BOLT{br['index']}',), SECTION='CERCLE', "
                f"CARA='R', VALE={_fmt(r)}),")
        for rr in remotes:
            b.w("    _F(GROUP_MA=('%s',), SECTION='CERCLE', CARA='R', VALE=0.5)," % (
                rr.get("group") or group_name("RPT", rr.get("analysis_index", ai), rr["load_index"])))
        b.w("))")
        b.w()
        b.w("# RBE3 spiders: master nodes drive their face sets with a")
        b.w("# distributing (deformable) coupling, like Ansys 'Deformable' behavior")
        b.w("spider = AFFE_CHAR_MECA(MODELE=model, LIAISON_RBE3=(")
        for br in bolts:
            for side in ("A", "B"):
                b.w(f"    _F(GROUP_NO_MAIT='BN{br['index']}{side}',")
                b.w("       DDL_MAIT=('DX', 'DY', 'DZ', 'DRX', 'DRY', 'DRZ'),")
                b.w(f"       GROUP_NO_ESCL=('BF{side}{br['index']}',),")
                b.w("       DDL_ESCL=('DX-DY-DZ',), COEF_ESCL=(1.0,)),")
        for rr in remotes:
            b.w("    _F(GROUP_NO_MAIT='%s'," % group_name(
                "RPN", rr.get("analysis_index", ai), rr["load_index"]))
            b.w("       DDL_MAIT=('DX', 'DY', 'DZ', 'DRX', 'DRY', 'DRZ'),")
            b.w("       GROUP_NO_ESCL=('%s',)," % group_name(
                "LOA", rr.get("analysis_index", ai), rr["load_index"]))
            b.w("       DDL_ESCL=('DX-DY-DZ',), COEF_ESCL=(1.0,)),")
        b.w("))")
        b.w()

    # tie constraints (bonded, non-conformal)
    ties = [t for t in setup.get("ties", [])
            if t.get("slave_faces") and t.get("master_solid")]
    # A BONDED contact is the same constraint: glue the slave face onto the
    # master's volume. Keeping it linear matters — a bonded interface has no
    # status to solve for, so paying for a Newton loop would buy nothing.
    # A frictional interface being checked rather than solved is glued for
    # the solve: stuck and bonded are the same constraint.
    bonded = [c for c in active_contacts(setup, mesh_stats)
              if solves_linearly(c)]
    if ties or bonded:
        b.w("# tied (glued) face-to-volume constraints for non-conformal interfaces")
        b.w("tiec = AFFE_CHAR_MECA(MODELE=model, LIAISON_MAIL=(")
        for i, t in enumerate(ties):
            b.w(f"    _F(GROUP_MA_MAIT=('V{int(t['master_solid'])}',),")
            b.w(f"       GROUP_MA_ESCL=('TIE{i + 1}',), TYPE_RACCORD='MASSIF'),")
        for c in bonded:
            master = int((c.get("solids") or [0])[0])
            b.w(f"    _F(GROUP_MA_MAIT=('V{master}',),")
            b.w(f"       GROUP_MA_ESCL=('{c['gb']}',), TYPE_RACCORD='MASSIF'),")
        b.w("))")
        b.w()

    b.constraint_charges = []
    if beam_groups:
        b.constraint_charges.append("spider")
    if ties or bonded:
        b.constraint_charges.append("tiec")
    b.has_bolts = bool(bolts)
    b.has_beams = bool(beam_groups)
    b.bolts = bolts
    b.remotes = remotes


def is_complete_bolt(b: dict) -> bool:
    """A bolt that will actually be meshed: both sides have faces."""
    return bool(b.get("side_a_faces")) and bool(b.get("side_b_faces"))


def _active_bolts(setup: dict, mesh_stats: dict) -> list:
    """Join bolt setup entries with the geometric records from mesh time.

    Matched by ID, and the ID SETS must agree. Comparing counts was not
    enough: delete one bolt and add another — which is exactly what patterning
    onto a different hole does — and the count is unchanged while the new
    bolt has no mesh record. It would then be dropped here silently, and the
    model would solve with a joint that is in the tree and in no matrix.
    """
    recs = {r.get("id"): r for r in mesh_stats.get("bolts", [])}
    live = [b for b in setup.get("bolts", []) if is_complete_bolt(b)]
    live_ids = {b.get("id") for b in live}
    mesh_ids = set(recs)
    if live_ids != mesh_ids:
        added = len(live_ids - mesh_ids)
        gone = len(mesh_ids - live_ids)
        detail = ", ".join(filter(None, [
            f"{added} added" if added else "",
            f"{gone} removed" if gone else ""]))
        raise ValueError(
            f"The mesh does not match the bolts ({detail}) — bolt beams are "
            "built at mesh time, so re-mesh before solving.")
    return [{**recs[b["id"]], "cfg": b} for b in live]


def _active_remotes(analysis: dict, ai: int, mesh_stats: dict) -> list:
    """Remote loads of THIS analysis, joined with their mesh-time records."""
    recs = {r.get("id"): r for r in mesh_stats.get("remotes", [])}
    out = []
    for l in analysis.get("loads", []):
        if l.get("type") != "remote":
            continue
        rec = recs.get(l.get("id"))
        if rec is None:
            raise ValueError("Mesh is older than the remote-load setup — "
                             "re-mesh before solving.")
        out.append({**rec, "cfg": l})
    return out


def _cara_arg(b: CommBuild) -> str:
    return " CARA_ELEM=cara," if getattr(b, "has_beams", False) else ""


def preloaded_bolts(setup: dict, mesh_stats: dict) -> list:
    """[{index, name, F}] for every bolt carrying a preload.

    The caller needs the targets to calibrate against; see `_preload_charge`
    for why the requested force is not the force the model ends up with.
    """
    out = []
    for br in _active_bolts(setup, mesh_stats):
        F = float(br["cfg"].get("preload_N") or 0.0)
        if F > 0:
            out.append({"index": br["index"], "F": F,
                        "name": br["cfg"].get("name") or f"Bolt {br['index']}"})
    return out


def _preload_charge(b: CommBuild, scale: dict = None) -> "str|None":
    """PRE_EPSI axial pre-strain per preloaded bolt.

    PRE_EPSI imposes a *shortening*, not a force. The bolt is a spring in
    parallel with the clamped parts, so they take back part of it and the
    shank settles at

        F_achieved = F_requested * delta_S / (delta_S + delta_P)

    which for a normal steel joint is 15% low and for an aluminium one 35%.
    EPX = -F/(E*A) alone is therefore not the preload the engineer asked for.
    `scale` carries the per-bolt correction measured by a calibration run
    (see `server.calibrate_preload`); without it this writes the raw,
    uncorrected strain.
    """
    scale = scale or {}
    items = []
    for br in getattr(b, "bolts", []):
        cfg = br["cfg"]
        F = float(cfg.get("preload_N") or 0.0)
        if F <= 0:
            continue
        E = float(cfg.get("E_GPa", 210.0)) * 1000.0
        A = bolt_area(cfg)
        items.append((br["index"], -F * float(scale.get(br["index"], 1.0)) / (E * A)))
    if not items:
        return None
    b.w("preload = AFFE_CHAR_MECA(MODELE=model, PRE_EPSI=(")
    for idx, eps in items:
        b.w(f"    _F(GROUP_MA=('BOLT{idx}',), EPX={_fmt(eps)}),")
    b.w("))")
    b.w()
    return "preload"


def _bolt_forces_out(b: CommBuild, result_var: str) -> None:
    """EFGE_ELNO on the beam ends -> per-bolt N/V/M table on unit 36."""
    if not getattr(b, "has_bolts", False):
        return
    beam_groups = _group_tuple([f"BOLT{br['index']}" for br in b.bolts])
    bolts = list(b.bolts)

    def bolt_block(x):
        x.w(f"{result_var} = CALC_CHAMP(reuse={result_var}, RESULTAT={result_var},")
        x.w(f"                CARA_ELEM=cara, GROUP_MA={beam_groups},")
        x.w("                CONTRAINTE=('EFGE_ELNO',))")
        for br in bolts:
            for side in ("A", "B"):
                x.w(f"bt{br['index']}{side} = POST_RELEVE_T(ACTION=_F(")
                x.w(f"    INTITULE='BOLT{br['index']}_{side}', OPERATION='EXTRACTION',")
                x.w(f"    RESULTAT={result_var}, NOM_CHAM='EFGE_ELNO',")
                x.w(f"    GROUP_NO='BN{br['index']}{side}', TOUT_CMP='OUI'))")
                x.w(f"IMPR_TABLE(TABLE=bt{br['index']}{side}, UNITE=36, "
                    f"FORMAT='TABLEAU', SEPARATEUR=',')")
        x.result_files.append((36, "bolt_forces.csv"))
    _optional(b, "bolt end forces", bolt_block)


def _slip_check_out(b: CommBuild, contacts: list) -> None:
    """Interface stress at every frictional interface being solved bonded.

    The stress tensor at the interface nodes is all the check needs: the
    traction across the surface is sigma . n, and `slip.py` splits it into
    pressure and shear. Nothing new is asked of the solver — SIGM_NOEU is
    already computed for the contour plots, and POST_RELEVE_T already pulls
    tables at named groups everywhere else in this file.
    """
    checked = slip_checked(contacts)
    if not checked:
        return

    def block(x):
        for c in checked:
            x.w(f"sc{c['index']} = POST_RELEVE_T(ACTION=_F(")
            x.w(f"    INTITULE='CONTACT{c['index']}', OPERATION='EXTRACTION',")
            x.w("    RESULTAT=res, NOM_CHAM='SIGM_NOEU',")
            x.w(f"    GROUP_NO='{c['ga']}',")
            x.w("    NOM_CMP=('SIXX', 'SIYY', 'SIZZ', 'SIXY', 'SIXZ', 'SIYZ')))")
            x.w(f"IMPR_TABLE(TABLE=sc{c['index']}, UNITE=34, "
                "FORMAT='TABLEAU', SEPARATEUR=',')")
        x.result_files.append((34, "contact_check.csv"))
    _optional(b, "interface stress for the slip check", block)


def _supports(b: CommBuild, analysis: dict, ai: int) -> str:
    ddl_items, face_items = [], []
    for i, s in enumerate(analysis.get("supports", [])):
        if not s.get("faces"):
            continue
        g = group_name("SUP", ai, i + 1)
        stype = s.get("type", "fixed")
        if stype == "fixed":
            ddl_items.append(f"_F(GROUP_MA=('{g}',), DX=0.0, DY=0.0, DZ=0.0)")
        elif stype == "frictionless":
            # normal-only constraint = Ansys Frictionless Support / symmetry
            face_items.append(f"_F(GROUP_MA=('{g}',), DNOR=0.0)")
        else:  # prescribed displacement; None => leave DOF free
            comps = []
            for c, key in (("DX", "ux"), ("DY", "uy"), ("DZ", "uz")):
                v = s.get(key)
                if v is not None:
                    comps.append(f"{c}={_fmt(v)}")
            if comps:
                ddl_items.append(f"_F(GROUP_MA=('{g}',), {', '.join(comps)})")
    if not ddl_items and not face_items:
        raise ValueError(f"'{analysis.get('name', 'Analysis')}' has no support with "
                         "faces — add one under this analysis.")
    b.w("fix = AFFE_CHAR_MECA(MODELE=model,")
    if ddl_items:
        b.w("    DDL_IMPO=(")
        for it in ddl_items:
            b.w(f"        {it},")
        b.w("    ),")
    if face_items:
        b.w("    FACE_IMPO=(")
        for it in face_items:
            b.w(f"        {it},")
        b.w("    ),")
    b.w(")")
    b.w()
    return "fix"


def _loads(b: CommBuild, analysis: dict, ai: int, meta: dict, var: str = "loadc",
           harmonic: bool = False) -> "str|None":
    """Emit one AFFE_CHAR_MECA holding every load. Returns var name or None.
    harmonic=True skips body loads that make no sense as a harmonic
    excitation (rotation)."""
    force_items, pres_items, nodal_items, grav, rot = [], [], [], None, None
    areas = {f["tag"]: f["area"] for f in meta.get("faces", [])}
    for i, l in enumerate(analysis.get("loads", [])):
        t = l.get("type")
        g = group_name("LOA", ai, i + 1)
        if t == "force" and l.get("faces"):
            area = sum(areas.get(int(ft), 0.0) for ft in l["faces"])
            if area <= 0:
                raise ValueError(f"Load '{l.get('name', g)}': face area is zero")
            fx = float(l.get("fx", 0)) / area
            fy = float(l.get("fy", 0)) / area
            fz = float(l.get("fz", 0)) / area
            force_items.append(
                f"_F(GROUP_MA=('{g}',), FX={_fmt(fx)}, FY={_fmt(fy)}, FZ={_fmt(fz)})")
        elif t == "pressure" and l.get("faces"):
            pres_items.append(f"_F(GROUP_MA=('{g}',), PRES={_fmt(l.get('pressure', 0))})")
        elif t == "remote" and l.get("faces"):
            # applied at the RBE3 master node created at mesh time
            comps = []
            for c, key in (("FX", "fx"), ("FY", "fy"), ("FZ", "fz"),
                           ("MX", "mx"), ("MY", "my"), ("MZ", "mz")):
                v = float(l.get(key) or 0.0)
                if v != 0.0:
                    comps.append(f"{c}={_fmt(v)}")
            if comps:
                nodal_items.append(
                    f"_F(GROUP_NO=('{group_name('RPN', ai, i + 1)}',), {', '.join(comps)})")
        elif t == "gravity" and not harmonic:
            gdir = l.get("g", [0, 0, -1])
            n = math.sqrt(sum(c * c for c in gdir)) or 1.0
            gmag = float(l.get("g_mag", 1.0)) * G_MM
            grav = (gmag, [c / n for c in gdir])
        elif t == "rotation" and not harmonic:
            if rot is not None:
                raise ValueError("Only one rotational-velocity load is supported.")
            ax = l.get("axis", [0, 0, 1])
            n = math.sqrt(sum(c * c for c in ax)) or 1.0
            omega = float(l.get("rpm", 0.0)) * 2.0 * math.pi / 60.0
            ctr = l.get("center", [0, 0, 0])
            rot = (omega, [c / n for c in ax], ctr)
    if not (force_items or pres_items or nodal_items or grav or rot):
        return None
    b.w(f"{var} = AFFE_CHAR_MECA(MODELE=model,")
    if force_items:
        b.w("    FORCE_FACE=(")
        for it in force_items:
            b.w(f"        {it},")
        b.w("    ),")
    if pres_items:
        b.w("    PRES_REP=(")
        for it in pres_items:
            b.w(f"        {it},")
        b.w("    ),")
    if nodal_items:
        b.w("    FORCE_NODALE=(")
        for it in nodal_items:
            b.w(f"        {it},")
        b.w("    ),")
    if grav:
        gmag, d = grav
        b.w(f"    PESANTEUR=_F(GRAVITE={_fmt(gmag)}, DIRECTION=({_fmt(d[0])}, {_fmt(d[1])}, {_fmt(d[2])})),")
    if rot:
        omega, ax, ctr = rot
        b.w(f"    ROTATION=_F(VITESSE={_fmt(omega)},")
        b.w(f"                AXE=({_fmt(ax[0])}, {_fmt(ax[1])}, {_fmt(ax[2])}),")
        b.w(f"                CENTRE=({_fmt(ctr[0])}, {_fmt(ctr[1])}, {_fmt(ctr[2])})),")
    b.w(")")
    b.w()
    return var


def _support_groups(analysis: dict, ai: int) -> list:
    return [group_name("SUP", ai, i + 1)
            for i, s in enumerate(analysis.get("supports", [])) if s.get("faces")]


